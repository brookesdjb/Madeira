"""Generate a freestanding x86-64 ELF: Linux sys_exit(42), then unreachable UD2.

No host linker or libc is needed. The existing FEXBridge ELF loader executes it.
"""
from pathlib import Path
import struct


def executable():
    code = bytes.fromhex("b83c000000 bf2a000000 0f05 0f0b")
    base, offset = 0x400000, 64 + 56
    size = offset + len(code)
    ident = b"\x7fELF\x02\x01\x01" + b"\0" * 9
    header = struct.pack("<16sHHIQQQIHHHHHH", ident, 2, 62, 1, base + offset,
                         64, 0, 0, 64, 56, 1, 0, 0, 0)
    segment = struct.pack("<IIQQQQQQ", 1, 5, 0, base, base, size, size, 4096)
    return header + segment + code


def header():
    data = executable()
    rows = [", ".join(f"0x{v:02x}" for v in data[i:i+12]) for i in range(0, len(data), 12)]
    return ("// Generated by automation/generate_exit42.py; debug automation only.\n"
            "static const unsigned char automation_exit42_elf[] = {\n    "
            + ",\n    ".join(rows) + "\n};\n")


if __name__ == "__main__":
    (Path(__file__).resolve().parents[1] / "app/Madeira/automation_exit42.h").write_text(header())
